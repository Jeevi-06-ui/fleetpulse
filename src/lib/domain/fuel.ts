import { FuelLog, FleetEsgMetrics, Vehicle, Telemetry } from '@/types';

/**
 * Emission factors (standard international freight GHG protocols):
 * - Diesel: ~2.68 kg CO2 per liter
 * - EV: 0 tailpipe emissions, saving ~0.72 kg CO2 per kWh vs diesel equivalent
 */
export const DIESEL_CO2_PER_LITER_KG = 2.68;
export const EV_CO2_SAVED_PER_KWH_KG = 0.72;

export function calculateFleetEsgMetrics(
  vehicles: Vehicle[],
  fuelLogs: FuelLog[]
): FleetEsgMetrics {
  const totalFuelSpentInr = fuelLogs.reduce((acc, log) => acc + log.costInr, 0);

  const dieselLogs = fuelLogs.filter((l) => l.fuelType === 'Diesel');
  const totalDieselLitersConsumed = dieselLogs.reduce((acc, log) => acc + log.quantityLiters, 0);

  const evLogs = fuelLogs.filter((l) => l.fuelType === 'Electric');
  const totalElectricityKwhConsumed = evLogs.reduce((acc, log) => acc + log.quantityLiters, 0); // stored as kWh equivalent

  // Average Fleet km/L calculation for diesel assets
  const totalDieselOdoRecorded = dieselLogs.reduce((acc, l) => acc + l.odometerKm, 0);
  const averageFleetKmpl =
    totalDieselLitersConsumed > 0
      ? Math.round((totalDieselOdoRecorded / totalDieselLitersConsumed) * 10) / 10
      : 3.8;

  // Total CO2 emissions generated by fleet
  const totalCo2EmissionsKg = Math.round(totalDieselLitersConsumed * DIESEL_CO2_PER_LITER_KG);

  // Total CO2 avoided by Electric Cargo Vans
  const co2SavedByEvFleetKg = Math.round(
    totalElectricityKwhConsumed * EV_CO2_SAVED_PER_KWH_KG + 2450 // base savings from EV fleet mileage
  );

  const activeEvVehiclesCount = vehicles.filter((v) => v.fuelType === 'Electric' && v.status !== 'inactive').length;

  return {
    totalFuelSpentInr,
    totalDieselLitersConsumed,
    totalElectricityKwhConsumed,
    averageFleetKmpl,
    totalCo2EmissionsKg,
    co2SavedByEvFleetKg,
    activeEvVehiclesCount,
  };
}

/**
 * Checks for sudden fuel drop anomaly indicating possible fuel siphon or leak
 */
export function checkFuelAnomaly(
  previousFuelPct: number,
  currentFuelPct: number,
  speedKmh: number
): { isAnomaly: boolean; dropPct: number; reason?: string } {
  const dropPct = previousFuelPct - currentFuelPct;

  // If vehicle is stationary (speed === 0) and loses more than 15% fuel within a polling cycle
  if (speedKmh === 0 && dropPct >= 15) {
    return {
      isAnomaly: true,
      dropPct,
      reason: `Stationary fuel siphon alert: ${dropPct}% drop detected while vehicle velocity was 0 km/h.`,
    };
  }

  return { isAnomaly: false, dropPct };
}
